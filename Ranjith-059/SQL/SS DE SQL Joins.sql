Q1. Multi-column Join

Write an SQL query to display each employee’s name and ID along with the project name and department ID of the project, but only for employees whose project and department IDs both match with the Projects table.

Q2. Three-table Join

Write an SQL query to display each employee’s name, their department name, and the project name they are working on. Include employees even if they are not assigned to any project.

Q3. Display All Employees

Write an SQL query to display all records from the Employees table.

Q4. Self Join – Employee with Full Manager Details

Write an SQL query to display each employee’s name along with all details of their manager from the Employees table.

Q5. Self Join – Employee and Manager Name

Write an SQL query to display each employee’s name together with their manager’s name from the Employees table.

Q6. Self Join – Skip-level Manager

Write an SQL query to display each employee’s name, their direct manager’s name, and their skip-level manager’s name (i.e., manager’s manager), if available.
